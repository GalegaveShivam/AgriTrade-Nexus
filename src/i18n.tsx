interface LanguageContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, defaultText?: string) => string;
  getCropName: (categoryOrTitle: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key, defaultText) => defaultText || key,
  getCropName: (c) => c,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguage>(() => {
    try {
      const saved = localStorage.getItem('agritrade_lang');
      if (saved && LANGUAGES.some((l) => l.code === saved)) {
        return saved as SupportedLanguage;
      }
    } catch {
      // ignore
    }
    return 'en';
  });

  // Sync html lang tag
  useEffect(() => {
    try {
      document.documentElement.lang = language;
    } catch {
      // ignore
    }
  }, [language]);

  const setLanguage = (lang: SupportedLanguage) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('agritrade_lang', lang);
      document.documentElement.lang = lang;
    } catch {
      // ignore
    }
  };

  const t = (key: string, defaultText?: string): string => {
    const langDict = translations[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    const enDict = translations.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return defaultText || key;
  };

  const getCropName = (categoryOrTitle: string): string => {
    const lower = categoryOrTitle.toLowerCase();
    if (lower.includes('wheat') || lower.includes('sharbati') || lower.includes('lokwan')) {
      return t('wheat', 'Wheat');
    }
    if (lower.includes('mustard') || lower.includes('sarson') || lower.includes('rai')) {
      return t('mustard', 'Mustard');
    }
    if (lower.includes('soybean') || lower.includes('soya')) {
      return t('soybean', 'Soybean');
    }
    if (lower.includes('chana') || lower.includes('gram') || lower.includes('chickpea') || lower.includes('tur')) {
      return t('chana', 'Gram / Pulses');
    }
    if (lower.includes('maize') || lower.includes('corn') || lower.includes('makka')) {
      return t('maize', 'Maize');
    }
    if (lower.includes('rice') || lower.includes('basmati') || lower.includes('paddy') || lower.includes('dhan')) {
      return t('rice', 'Rice / Paddy');
    }
    if (lower.includes('groundnut') || lower.includes('peanut') || lower.includes('moongphali') || lower.includes('shengdana')) {
      return t('groundnut', 'Groundnut');
    }
    if (lower.includes('cotton') || lower.includes('kapas')) {
      return t('cotton', 'Cotton');
    }
    if (lower.includes('chilli') || lower.includes('mirch')) {
      return t('chilli', 'Red Chilli');
    }
    if (lower.includes('turmeric') || lower.includes('haldi')) {
      return t('turmeric', 'Turmeric');
    }
    if (lower.includes('pepper') || lower.includes('kali mirch')) {
      return t('pepper', 'Black Pepper');
    }
    if (lower.includes('cardamom') || lower.includes('elaichi')) {
      return t('cardamom', 'Cardamom');
    }
    if (lower.includes('jute') || lower.includes('pat')) {
      return t('jute', 'Raw Jute');
    }
    if (lower.includes('potato') || lower.includes('aloo')) {
      return t('potato', 'Potato');
    }
    if (lower.includes('millet') || lower.includes('ragi') || lower.includes('mandia') || lower.includes('bajra')) {
      return t('ragi', 'Millets / Ragi');
    }
    return categoryOrTitle;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, getCropName }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
